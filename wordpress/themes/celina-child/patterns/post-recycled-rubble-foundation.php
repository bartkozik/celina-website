<!-- wp:heading -->
<h2 class="wp-block-heading">CELINA Uses Celina Elementary School Rubble to Build Foundations</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Growth brings opportunity, but it also requires investment. Over the past several years, CELINA has continued to expand manufacturing capabilities while serving customers across commercial, industrial, military, and government markets.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>To support that growth, we expanded our consolidation and logistics yard from approximately six acres to nine acres, creating additional space for staging, container loading, and material movement. This investment strengthens our ability to serve customers efficiently while preparing our campus for continued growth in the years ahead.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">A Foundation With Local History</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>There is something uniquely meaningful about the material beneath this expansion. The concrete that once formed the floors and foundations of a school where thousands of local students began their education has been transformed into the base of infrastructure that supports manufacturing, exports, and careers in Mercer County, Ohio.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Rather than sending those materials to a landfill, they are being crushed, processed, and engineered into a foundation capable of supporting some of the largest equipment operating on CELINA's manufacturing campus — including heavy forklifts moving fully loaded shipping containers weighing well over 100,000 pounds.</p>
<!-- /wp:paragraph -->

<!-- wp:pullquote -->
<figure class="wp-block-pullquote"><blockquote><p>One generation's investment in education is helping support the next generation of opportunity.</p></blockquote></figure>
<!-- /wp:pullquote -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Manufacturing and Community Go Hand in Hand</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>At CELINA, we have always believed that our success is closely connected to the success of our surrounding communities. Our employees graduated from local schools. Our families live here. Our suppliers, partners, and customers know Mercer County as a place where people take pride in their work and invest in the future.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Projects like this remind us that growth is not just measured in square footage or production capacity. It is measured in the partnerships that make that growth possible.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The collaboration between Celina City Schools, construction teams, and local industry demonstrates how organizations can work together to create value that extends well beyond a single project. Materials that once served one purpose now support another, continuing to benefit the community in an entirely new way.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">CELINA Looking Forward</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The expansion of our logistics yard represents more than additional operational capacity. It is another investment in our ability to manufacture, innovate, and serve customers for decades to come.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>As new generations of students begin their education in modern classrooms across town, materials from the former Celina Elementary School will continue to serve the community in a different way — supporting the movement of products built by local craftspeople and shipped to customers across the nation and around the globe.</p>
<!-- /wp:paragraph -->

