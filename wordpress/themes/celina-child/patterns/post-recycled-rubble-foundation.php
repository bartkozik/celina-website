<!-- wp:paragraph {"className":"celina-article-intro"} -->
<p class="celina-article-intro">For generations of Celina families, the former Celina Elementary School was one of those places. It was where students learned to read, made lifelong friends, and took the first steps in their educational journey. While the building has now made way for the next generation of schools, its story is not over.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"celina-article-intro"} -->
<p class="celina-article-intro">Today, that same foundation is helping build something new at CELINA.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>As part of the redevelopment of the Celina City Schools campus, CELINA processed and reused concrete and aggregate from the former Celina Elementary School as the structural base for the expansion of our consolidation and logistics yard. What once supported classrooms and hallways will now support the movement of products manufactured in Celina and shipped to customers around the world.</p>
<!-- /wp:paragraph -->

