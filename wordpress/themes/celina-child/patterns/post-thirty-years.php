<h2 class="wp-block-heading">Built by Our People</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Most people see the finished product.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>What they don't always see are the hundreds of decisions, skilled hands, and years of experience that come together before a product ever reaches a customer.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Every department throughout our facility contributes to that process. Materials are carefully prepared. Components are cut and fabricated. Fabrics are welded and sewn. Hardware is assembled. Graphics are applied. Every product is inspected before it leaves our facility.</p>
<!-- /wp:paragraph -->

<!-- wp:image {"sizeSlug":"large"} -->
<figure class="wp-block-image size-large"><img src="<?php echo esc_url( get_theme_file_uri( 'assets/images/article-placeholder.svg' ) ); ?>" alt="Skilled technicians fabricating and sewing textile products on the manufacturing floor."/><figcaption class="wp-element-caption">Skilled technicians fabricating and sewing textile products on the manufacturing floor.</figcaption></figure>
<!-- /wp:image -->

<!-- wp:paragraph -->
<p>Each workstation represents one step in a much larger journey. Every employee contributes to the final product, and every step directly influences the quality, durability, and performance our customers expect.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>That commitment to craftsmanship has remained one of our defining characteristics for thirty years.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Rather than outsourcing every stage of production, we've continued investing in in-house manufacturing capabilities. Maintaining control over key processes allows us to uphold consistent quality standards, continuously improve our products, and provide dependable replacement parts and long-term customer support.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>It's an approach that requires investment, experience, and teamwork, but it's one we believe is worth it because it allows us to stand behind everything we build.</p>
