<!-- wp:paragraph -->
<p>As customer needs evolved, so did we. We expanded beyond rentals and invested in designing and manufacturing products ourselves. That decision laid the foundation for everything that followed.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Over the years, we have grown into a trusted manufacturer serving customers across commercial, industrial, and government markets. While our capabilities have expanded dramatically, our purpose has remained remarkably consistent: build quality products, support customers long after the sale, and conduct business with integrity.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Thirty Years Built by People</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>If there is one thing we have learned over the past three decades, it is that great products are built by great people.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Our greatest achievement is not measured by the products we have manufactured or the markets we have entered. It is measured by the relationships we have built along the way.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Many members of our team have spent years — and in some cases decades — helping refine CELINA manufacturing processes, improve products, mentor new employees, and solve challenges together. Their experience, craftsmanship, and pride in their work can be seen in every tent, shelter, and textile solution that leaves our facility.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We are equally grateful to the customers who have trusted us with their businesses, the suppliers and partners who have worked alongside us, and the surrounding communities that supported us from the very beginning.</p>
<!-- /wp:paragraph -->

<!-- wp:pullquote -->
<figure class="wp-block-pullquote"><blockquote><p>From the very beginning, this company was built on family, hard work, and the support of this community. What started as a small idea grew because people believed in us; our employees, our customers, and our neighbors.</p><cite>Janice Team Member 4, Co-Founder of CELINA</cite></blockquote></figure>
<!-- /wp:pullquote -->

<!-- wp:paragraph -->
<p>While we are celebrating thirty years of business, we are really celebrating thirty years of people working together toward a common goal.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Built by Our People</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Most people see the finished product. What they do not always see are the hundreds of decisions, skilled hands, and years of experience that come together before a product ever reaches a customer.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Every department throughout our facility contributes to that process. Materials are carefully prepared. Components are cut and fabricated. Fabrics are welded and sewn. Hardware is assembled. Graphics are applied. Every product is inspected before it leaves our facility.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Each workstation represents one step in a much larger journey. Every employee contributes to the final product, and every step directly influences the quality, durability, and performance our customers expect.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Rather than outsourcing every stage of production, we have continued investing in in-house manufacturing capabilities. Maintaining control over key processes allows us to uphold consistent quality standards, continuously improve our products, and provide dependable replacement parts and long-term customer support.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Growing Together With Our Community</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our story has never been ours alone. From the beginning, we have grown alongside the people and organizations that make Mercer County and the surrounding areas such a special place.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Employees choose to build careers with us. Local schools and educators help prepare future members of our workforce. Local leaders, businesses, and community organizations support our continued growth as new opportunities emerge.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Opening our doors during our anniversary celebration allows us to introduce the people behind the products, showcase the craftsmanship that goes into every project, and celebrate the partnerships that have made thirty years of growth possible.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">The Values That Have Not Changed</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Over the past three decades, we have introduced new products, entered new markets, invested in new equipment, and expanded our manufacturing capabilities. But the values that guide us today are the same ones that guided us in 1996.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We believe quality should never be compromised. We believe in building products that make us proud. We believe in supporting customers long after a purchase is made. We believe that lasting relationships matter more than short-term successes. And we believe our greatest investment will always be the people who make everything we do possible.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Looking Toward the Future</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Reaching thirty years is an important milestone, but it is not the finish line for CELINA Manufacturing. Every generation of employees has contributed something meaningful to our story, and we are excited about what the next generation will build.</p>
