<p>Every business starts with an idea, but lasting businesses are built through consistency, determination, and the willingness to keep improving. That's exactly how our story began.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In 1996, we started as a small event rental business in Celina, Ohio. Like many family businesses, our early years were shaped by hard work, long days, and a commitment to doing right by every customer. Those early experiences taught us lessons that continue to influence how we operate today: pay attention to the details, stand behind what you build, and never stop looking for ways to improve.</p>
<!-- /wp:paragraph -->

