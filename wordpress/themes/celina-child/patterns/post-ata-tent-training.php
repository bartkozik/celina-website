<!-- wp:paragraph -->
<p>Education benefits everyone involved:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><li>Customers make more informed decisions.</li><li>Installers work safer.</li><li>Equipment lasts longer.</li><li>Projects run more efficiently.</li><li>The industry as a whole becomes stronger.</li></ul>
<!-- /wp:list -->

