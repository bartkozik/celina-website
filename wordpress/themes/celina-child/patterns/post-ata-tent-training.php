<!-- wp:heading -->
<h2 class="wp-block-heading">CELINA Invests in More Than Products</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Earlier this year, CELINA welcomed professionals from across the tent-rental industry as host of the Advanced Textiles Association (ATA) Tent Rental Division (TRD) Boot Camp, a hands-on educational program focused on improving safety, installation techniques, engineering awareness, repairs, anchoring, and industry best practices.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The <a href="https://example.invalid/referencereference">ATA tent training at CELINA</a> combined classroom instruction, demonstrations, networking, and a tour of CELINA's manufacturing facility, giving attendees practical knowledge they could immediately take back to their organizations.</p>
<!-- /wp:paragraph -->

