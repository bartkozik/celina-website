<p class="celina-article-intro">What began in 1996 as a small event rental business in Celina, Ohio has grown into a global manufacturer serving commercial, industrial, and government customers around the world. Along the way, we've expanded our capabilities, welcomed incredible people to our team, and built lasting relationships with customers and partners. Through it all, we've stayed true to the values that shaped us from the beginning: quality, integrity, family, and community.</p>
